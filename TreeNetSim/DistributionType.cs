using System;

namespace TreeNetSim
{
    /// <summary>
    /// Типы распределений для генерации интервалов между пакетами
    /// </summary>
    public enum DistributionType
    {
        /// <summary>
        /// Детерминированное (фиксированные интервалы)
        /// Интервал = const
        /// </summary>
        Deterministic,

        /// <summary>
        /// Экспоненциальное (распределение Пуассона)
        /// Стандарт для моделирования сетевого трафика
        /// Среднее = λ
        /// </summary>
        Exponential,

        /// <summary>
        /// Распределение Парето (тяжёлый хвост)
        /// Для моделирования всплесков трафика
        /// Параметры: x_min, α
        /// </summary>
        Pareto,

        /// <summary>
        /// Нормальное (Гаусса)
        /// Для моделирования задержек
        /// Параметры: μ, σ
        /// </summary>
        Normal,

        /// <summary>
        /// Равномерное распределение
        /// Равновероятные интервалы в диапазоне [min, max]
        /// </summary>
        Uniform
    }
}